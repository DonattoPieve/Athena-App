/**
 * Português e inglês, com o português como chave.
 *
 * `t("Salvar")` devolve "Save" em inglês e "Salvar" em português. A chave ser
 * a própria frase em pt-BR tem duas consequências boas: o código continua
 * legível (não vira `t("settings.save")`), e uma frase que eu esqueci de
 * traduzir aparece em português em vez de aparecer como chave crua na tela.
 *
 * Trocar de idioma recarrega a janela. Não é preguiça de propagar estado: o
 * texto está espalhado por trinta componentes, vários deles guardam string em
 * `useState` (mensagem de erro, rótulo de comando), e um trocador reativo
 * deixaria pedaços no idioma antigo até a próxima interação. O reload custa
 * meio segundo e não erra.
 */
export type Idioma = "pt" | "en";

const CHAVE = "athena-lang";

/**
 * Fora do navegador este módulo tem que carregar sem explodir: os testes de
 * `scripts/` importam `progresso.ts`, que importa daqui, e lá não existe
 * `localStorage` nem `location`. Sem navegador o idioma é português.
 */
const NAVEGADOR = typeof window !== "undefined" && typeof localStorage !== "undefined";
const DEV = NAVEGADOR && location.port === "5173";

export function idioma(): Idioma {
  if (!NAVEGADOR) return "pt";
  return localStorage.getItem(CHAVE) === "en" ? "en" : "pt";
}

/** Lido uma vez: mudar de idioma passa por `trocarIdioma`, que recarrega. */
const ATUAL: Idioma = idioma();

export function trocarIdioma(l: Idioma) {
  if (!NAVEGADOR || l === ATUAL) return;
  localStorage.setItem(CHAVE, l);
  window.location.reload();
}

export function t(pt: string): string {
  if (ATUAL === "pt") return pt;
  const en = EN[pt];
  if (en === undefined) {
    // Só no dev: em produção uma frase sem tradução vira português na tela, e
    // gritar no console do usuário não conserta nada.
    if (DEV) console.warn("[i18n] sem tradução:", JSON.stringify(pt));
    return pt;
  }
  return en;
}

/**
 * Frase com pedaço variável, para não picotar a tradução em pedaços que a
 * ordem das palavras em inglês depois embaralha.
 *
 *   tf("{n} termos", { n: 4 })  ->  "4 terms"
 */
export function tf(pt: string, vars: Record<string, string | number>): string {
  return t(pt).replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

